/**
 * Generate and download CSV for sessions data
 */
export function generateSessionsCSV(sessions: Array<{
  id: string;
  meeting_title: string;
  host_name: string;
  date_time_start: string;
  date_time_end?: string;
  duration_hours?: number;
  participant_count_total: number;
  participant_count_viewing: number;
  meeting_type: string;
  source_language: string;
  target_languages: string[];
  cost: number;
  status: string;
}>, filename: string = 'sessions-export.csv') {

  // Transform data for CSV
  const csvData = sessions.map(session => ({
    'Session ID': session.id,
    'Meeting Title': session.meeting_title,
    'Host': session.host_name,
    'Date': formatDate(session.date_time_start),
    'Duration (hours)': session.duration_hours?.toFixed(2) || 'N/A',
    'Total Participants': session.participant_count_total,
    'Viewing Translations': session.participant_count_viewing,
    'Meeting Type': session.meeting_type,
    'Source Language': session.source_language.toUpperCase(),
    'Target Languages': session.target_languages.map(l => l.toUpperCase()).join('; '),
    'Cost': session.cost.toFixed(2),
    'Status': session.status.toUpperCase()
  }));

  // Generate CSV
  const csv = Papa.unparse(csvData);

  // Download
  downloadCSV(csv, filename);
}

/**
 * Generate and download CSV for invoice data
 */
export function generateInvoiceCSV(invoice: {
  id: string;
  billing_period_start: string;
  billing_period_end: string;
  status: string;
  session_charges: Array<{
    session_date: string;
    tier_used: string;
    duration_hours: number;
    rate_per_hour: number;
    charge: number;
  }>;
  total_amount: number;
}, filename?: string) {

  // Transform data for CSV
  const csvData = invoice.session_charges.map(charge => ({
    'Invoice ID': invoice.id,
    'Billing Period': `${formatDate(invoice.billing_period_start)} - ${formatDate(invoice.billing_period_end)}`,
    'Session Date': formatDate(charge.session_date),
    'Tier': charge.tier_used,
    'Duration (hours)': charge.duration_hours.toFixed(2),
    'Rate per Hour': charge.rate_per_hour.toFixed(2),
    'Charge': charge.charge.toFixed(2),
    'Invoice Status': invoice.status.toUpperCase()
  }));

  // Add total row
  csvData.push({
    'Invoice ID': '',
    'Billing Period': '',
    'Session Date': '',
    'Tier': '',
    'Duration (hours)': '',
    'Rate per Hour': 'TOTAL:',
    'Charge': invoice.total_amount.toFixed(2),
    'Invoice Status': ''
  });

  // Generate CSV
  const csv = Papa.unparse(csvData);

  // Download
  downloadCSV(csv, filename || `invoice-${invoice.id}.csv`);
}

/**
 * Helper function to trigger CSV download
 */
function downloadCSV(csvContent: string, filename: string) {
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}


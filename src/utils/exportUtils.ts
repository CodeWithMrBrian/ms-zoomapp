/**
 * Simulate async download with delay (for realistic UX)
 */
export async function simulateDownload(
  downloadFn: () => void,
  delayMs: number = 800
): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(() => {
      downloadFn();
      resolve();
    }, delayMs);
  });
}
